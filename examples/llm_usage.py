def example_custom_wrapper():
    """Example with custom LLM wrapper for logging/monitoring."""
    print("\n" + "=" * 70)
    print("Example 8: Custom LLM Wrapper")
    print("=" * 70)
    
    class MonitoredLLM:
        """Custom LLM wrapper with logging and error handling."""
        
        def __init__(self, base_llm):
            self.base_llm = base_llm
            self.call_count = 0
            self.total_tokens = 0
        
        def __call__(self, prompt: str) -> str:
            self.call_count += 1
            print(f"📞 LLM Call #{self.call_count}")
            print(f"📝 Prompt length: {len(prompt)} chars")
            
            try:
                response = self.base_llm(prompt)
                print(f"✅ Response length: {len(response)} chars")
                return response
            except Exception as e:
                print(f"❌ LLM Error: {e}")
                raise
    
    # Example with mock LLM
    def mock_llm(prompt: str) -> str:
        return "This is a mock LLM response for testing."
    
    # Wrap it
    monitored_llm = MonitoredLLM(mock_llm)
    
    # Use it
    edi_result = parse("path/to/your/file.edi")
    val_result = validate(edi_result)
    
    result = explain(edi_result, val_result, llm=monitored_llm)
    print(f"\nTotal LLM calls: {monitored_llm.call_count}")



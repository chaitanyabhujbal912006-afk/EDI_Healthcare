# Example 7: Using Class-Based API
# ══════════════════════════════════════════════════════════════════════════════

def example_class_based():
    """Example using the class-based API for reusable explainer."""
    print("\n" + "=" * 70)
    print("Example 7: Class-Based API")
    print("=" * 70)
    
    try:
        from openai import OpenAI
        
        # Initialize OpenAI
        client = OpenAI(api_key="your-api-key-here")
        
        def llm(prompt: str) -> str:
            response = client.chat.completions.create(
                model="gpt-4",
                messages=[{"role": "user", "content": prompt}]
            )
            return response.choices[0].message.content
        
        # Create reusable explainer
        explainer = LLMExplainer(llm=llm)
        
        # Process multiple files
        files = ["file1.edi", "file2.edi", "file3.edi"]
        
        for filepath in files:
            edi_result = parse(filepath)
            val_result = validate(edi_result)
            
            # Get explanation
            result = explainer.explain(edi_result, val_result)
            print(f"\n{filepath}:")
            print(result.report[:200] + "...")  # Print first 200 chars
            
            # Ask questions
            answer = explainer.ask_followup(
                "Are there any critical errors?",
                edi_result,
                val_result
            )
            print(f"Q&A: {answer}")
        
    except ImportError:
        print("❌ OpenAI package not installed")
    except Exception as e:
        print(f"❌ Error: {e}")



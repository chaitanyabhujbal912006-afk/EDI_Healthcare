"""
ValidEDI LLM Usage Examples
============================

This example demonstrates how to use ValidEDI's LLM-powered explanations
with various LLM providers.

The LLM integration is provider-agnostic - you can use any LLM that accepts
a prompt string and returns a response string.
"""

from validedi import parse, validate
from validedi.llm import explain, ask_followup, LLMExplainer


# ══════════════════════════════════════════════════════════════════════════════
# Example 1: Using OpenAI GPT-4
# ══════════════════════════════════════════════════════════════════════════════

def example_openai():
    """Example using OpenAI's GPT-4."""
    print("=" * 70)
    print("Example 1: OpenAI GPT-4")
    print("=" * 70)
    
    try:
        from openai import OpenAI
        
        # Initialize OpenAI client
        client = OpenAI(api_key="your-api-key-here")
        
        # Create LLM callable
        def llm(prompt: str) -> str:
            response = client.chat.completions.create(
                model="gpt-4",
                messages=[{"role": "user", "content": prompt}],
                temperature=0.3,
                max_tokens=1200
            )
            return response.choices[0].message.content
        
        # Parse and validate EDI file
        edi_result = parse("path/to/your/file.edi")
        val_result = validate(edi_result)
        
        # Get explanation
        result = explain(edi_result, val_result, llm=llm)
        print(result.report)
        print(f"\nGenerated by: {result.source}")
        
        # Ask follow-up questions
        answer = ask_followup(
            "What is the total billed amount?",
            edi_result,
            val_result,
            llm=llm
        )
        print(f"\nQ&A: {answer}")
        
    except ImportError:
        print("❌ OpenAI package not installed. Install with: pip install openai")
    except Exception as e:
        print(f"❌ Error: {e}")


